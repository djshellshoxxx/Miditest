// Seeded synthetic captures used as regression fixtures. Run: node tools/make-fixtures.mjs  (writes tests/fixtures/*.capture.json)
import {writeFileSync} from 'node:fs';
import {serializeCapture} from '../lib/capture.js';

const rng=seed=>()=>((seed=(seed*1664525+1013904223)>>>0)/4294967296);
const mk=()=>({evs:[],t:0,add(bytes,dt=10){this.t+=dt;this.evs.push({t:this.t,deviceId:'fx',raw:bytes})}});

export const FIXTURES={
  'good-keyboard':{expect:{protocol:'ok',retrigger:'ok',pedal:'ok'},build(){const r=rng(1),m=mk();
    for(let k=36;k<=96;k++){const v=20+Math.round(r()*100);m.add([0x90,k,v],120);m.add([0x80,k,0],180)}
    for(let i=0;i<3;i++){m.add([0xB0,64,127],300);m.add([0xB0,64,0],400)}return m.evs}},
  'bouncing-keys':{expect:{retrigger:'investigate'},build(){const m=mk();
    for(let k=40;k<52;k++){m.add([0x90,k,70],200);m.add([0x80,k,0],150)}
    for(const k of [44,45,46]){m.add([0x80,k,0],300);m.add([0x90,k,5],8);m.add([0x80,k,0],100)}return m.evs}},
  'noisy-fader':{expect:{sweep:'attention'},build(){const m=mk();
    for(let v=0;v<=127;v++){m.add([0xB0,21,v],12);if(v%20===10){m.add([0xB0,21,Math.max(0,v-2)],12);m.add([0xB0,21,v],12)}}return m.evs}},
  'glitchy-encoder':{expect:{encoder:'attention'},build(){const m=mk();
    for(let i=0;i<30;i++){m.add([0xB0,16,1],30);if(i%7===3)m.add([0xB0,16,127],30)}
    for(let i=0;i<10;i++)m.add([0xB0,16,127],30);return m.evs}},
  'stuck-pedal':{expect:{pedal:'attention'},build(){const m=mk();
    for(const v of [0,127,0,127,0,127])m.add([0xB0,64,v],300);return m.evs}},
  'clock-dropouts':{expect:{link:'investigate'},build(){const m=mk();
    for(let i=0;i<120;i++){if(i>=50&&i<=54)m.t+=20;else m.add([0xF8],20)}return m.evs}}
};
if(process.argv[1]?.endsWith('make-fixtures.mjs')){
  for(const [name,f] of Object.entries(FIXTURES))writeFileSync(new URL('../tests/fixtures/'+name+'.capture.json',import.meta.url),serializeCapture(f.build(),{device:'Synthetic '+name,notes:'Generated by tools/make-fixtures.mjs'}));
  console.log('fixtures written');
}
